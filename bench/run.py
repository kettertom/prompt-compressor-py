#!/usr/bin/env python3
"""
prompt-compressor (Python) benchmark

    pip install tiktoken
    python bench/run.py

Same 8 prompts and must-keep facts as the JS package's benchmark
(github.com/kettertom/prompt-compressor/tree/main/bench), run against this
Python implementation:
  - tokens counted with a real tokenizer (OpenAI o200k_base via tiktoken)
  - every must-keep fact from facts.json is checked in the output
  - $ saved per 1M calls at a reference input price (PRICE_PER_MTOK, default 3)

Writes bench/results.md and bench/results.json.
"""
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import tiktoken  # noqa: E402
from prompt_compressor import compress  # noqa: E402

enc = tiktoken.get_encoding("o200k_base")
PRICE = float(os.environ.get("PRICE_PER_MTOK", "3"))
LEVELS = ["very-low", "low", "medium"]


def tokens(s: str) -> int:
    return len(enc.encode(s))


FENCE_JSON = re.compile(r"```json\s*([\s\S]*?)```", re.I)


def _strip(v):
    if isinstance(v, dict):
        return {k: _strip(x) for k, x in v.items() if not (x is None or x == "" or x == [])}
    if isinstance(v, list):
        return [_strip(x) for x in v if not (x is None or x == "" or x == [])]
    return v


def json_intact(original: str, output: str):
    """Every ```json block must still parse and hold the same data (minus null / "" / [] fields)."""
    a, b = FENCE_JSON.findall(original), FENCE_JSON.findall(output)
    if not a:
        return None
    if len(a) != len(b):
        return False
    try:
        return all(_strip(json.loads(x)) == _strip(json.loads(y)) for x, y in zip(a, b))
    except ValueError:
        return False


facts = json.loads((HERE / "facts.json").read_text())
rows = []
for path in sorted((HERE / "prompts").glob("*.txt")):
    text = path.read_text()
    meta = facts[path.name]
    bad = [f for f in meta["mustKeep"] if not re.search(f, text, re.I)]
    if bad:
        raise SystemExit(f"{path.name}: facts not in original: {bad}")
    before = tokens(text)
    for level in LEVELS:
        out = compress(text, level=level).output
        after = tokens(out)
        missing = [f for f in meta["mustKeep"] if not re.search(f, out, re.I)]
        rows.append(dict(
            file=path.name, label=meta["label"], level=level, before=before, after=after,
            pct=100 * (before - after) / before, factsKept=len(meta["mustKeep"]) - len(missing),
            factsTotal=len(meta["mustKeep"]), missing=missing, jsonIntact=json_intact(text, out), dollarsPer1MCalls=(before - after) * PRICE,
        ))

money = lambda n: f"${round(n):,}"  # noqa: E731
low = [r for r in rows if r["level"] == "low"]
md = "| Prompt | Tokens before | Tokens after | Saved | $ saved per 1M calls* | Must-keep facts kept |\n|---|---:|---:|---:|---:|:---:|\n"
for r in low:
    ok = " ✅" if r["factsKept"] == r["factsTotal"] else " ⚠️"
    md += f"| {r['label']} | {r['before']:,} | {r['after']:,} | **{r['pct']:.0f}%** | {money(r['dollarsPer1MCalls'])} | {r['factsKept']}/{r['factsTotal']}{ok} |\n"
tb, ta = sum(r["before"] for r in low), sum(r["after"] for r in low)
md += (f"| **Total** | **{tb:,}** | **{ta:,}** | **{100 * (tb - ta) / tb:.0f}%** | "
       f"**{money(sum(r['dollarsPer1MCalls'] for r in low))}** | "
       f"**{sum(r['factsKept'] for r in low)}/{sum(r['factsTotal'] for r in low)}** |\n")

md2 = "| Level | Avg. saved | Must-keep facts kept | JSON blocks intact |\n|---|---:|:---:|:---:|\n"
for level in LEVELS:
    lr = [r for r in rows if r["level"] == level]
    b, a = sum(r["before"] for r in lr), sum(r["after"] for r in lr)
    k, t = sum(r["factsKept"] for r in lr), sum(r["factsTotal"] for r in lr)
    js = [r for r in lr if r["jsonIntact"] is not None]
    ok = sum(1 for r in js if r["jsonIntact"])
    md2 += f"| `{level}` | {100 * (b - a) / b:.0f}% | {k}/{t} ({100 * k / t:.0f}%) | {ok}/{len(js)}{' ✅' if ok == len(js) else ' ❌'} |\n"

lost = [r for r in rows if r["missing"]]
md3 = ("\n".join(f"- `{r['level']}` · {r['label']}: lost {len(r['missing'])}/{r['factsTotal']}" for r in lost)
       + "\n\nThe exact facts lost are listed in [`bench/results.json`](results.json).\n") if lost else \
    "- None: every must-keep fact survived at every level.\n"

out = f"""<!-- generated by bench/run.py — do not edit by hand -->
### Results at the default level (`low`)

{md}
\\* At ${PRICE:g} per 1M input tokens. For your model, multiply by (your price ÷ {PRICE:g}). Tokens counted with OpenAI's `o200k_base` tokenizer.

### By risk level

{md2}
"JSON blocks intact" = every ```json block still parses and holds the same data as the original (null / empty fields are removed on purpose).

Facts lost (if any):

{md3}"""
(HERE / "results.md").write_text(out)
(HERE / "results.json").write_text(json.dumps({"tokenizer": "o200k_base", "pricePerMTok": PRICE, "rows": rows}, indent=2))
print(out)
